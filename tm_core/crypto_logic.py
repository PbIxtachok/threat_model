# -*- coding: utf-8 -*-
"""Логика приказа ФСБ России № 378: тип актуальных угроз → требуемый класс СКЗИ.

Применимость: ИСПДн (уровень защищённости «УЗ-N»), в которой для защиты
персональных данных используются средства криптографической защиты информации
(Profile.has_crypto).

Источники правил (формулировки — из текста приказа и ПП РФ № 1119):
  * Постановление Правительства РФ от 01.11.2012 № 1119: типы актуальных
    угроз — 1-й тип (угрозы, связанные с наличием недекларированных
    возможностей (НДВ) в системном ПО), 2-й тип (с НДВ в прикладном ПО),
    3-й тип (не связанные с НДВ). Актуальность типов по уровням
    защищённости: УЗ-1 и УЗ-2 → типы 1, 2, 3; УЗ-3 → типы 2, 3; УЗ-4 → тип 3.
  * Приказ ФСБ России от 10.07.2014 № 378 (п. 9«в», 18, 21, 26) — требуемый
    класс СКЗИ:
      УЗ-4: тип 3 → «КС1 и выше»;
      УЗ-3: тип 2 → «КВ и выше», тип 3 → «КС1 и выше»;
      УЗ-2: тип 1 → «КА», тип 2 → «КВ и выше», тип 3 → «КС1 и выше»;
      УЗ-1: тип 1 → «КА», тип 2 → «КВ и выше».
"""
from __future__ import annotations

from typing import Any, Dict, List, Optional

from .schema import Profile

# Актуальные типы угроз по уровням защищённости (ПП РФ № 1119):
# 1-й тип — угрозы, связанные с НДВ в системном ПО;
# 2-й тип — с НДВ в прикладном ПО; 3-й тип — не связанные с НДВ.
THREAT_TYPES_BY_UZ: Dict[str, List[int]] = {
    "УЗ-1": [1, 2, 3],
    "УЗ-2": [1, 2, 3],
    "УЗ-3": [2, 3],
    "УЗ-4": [3],
}

# Требуемый класс СКЗИ (приказ ФСБ № 378, п. 9«в», 18, 21, 26).
SKZI_CLASS_RULES: Dict[str, Dict[int, str]] = {
    "УЗ-1": {1: "КА", 2: "КВ и выше"},
    "УЗ-2": {1: "КА", 2: "КВ и выше", 3: "КС1 и выше"},
    "УЗ-3": {2: "КВ и выше", 3: "КС1 и выше"},
    "УЗ-4": {3: "КС1 и выше"},
}

# Строгость классов СКЗИ (базовое обозначение без суффикса «и выше»):
# чем больше ранг, тем строже класс.
_CLASS_RANK = {"КС1": 1, "КС2": 2, "КС3": 3, "КВ": 4, "КА": 5}


def _class_rank(class_str: str) -> int:
    base = str(class_str).replace(" и выше", "").strip()
    return _CLASS_RANK.get(base, 0)


def skzi_assessment(profile: Profile) -> Optional[Dict[str, Any]]:
    """Оценка требуемого класса СКЗИ по приказу ФСБ № 378.

    Возвращает None, если блок неприменим: уровень защищённости не
    начинается с «УЗ-» (не ИСПДн) или СКЗИ не применяются
    (``profile.has_crypto`` ложно).

    Иначе возвращает::

        {
          'uz': 'УЗ-2',
          'threat_types': [1, 2, 3],
          'rows': [{'type': 1, 'class': 'КА'}, ...],
          'min_class': 'КА'   # максимальный (наиболее строгий) из требуемых
        }
    """
    uz = str(profile.protection_level or "").strip()
    if not uz.startswith("УЗ-") or not profile.has_crypto:
        return None
    threat_types = THREAT_TYPES_BY_UZ.get(uz)
    rules = SKZI_CLASS_RULES.get(uz)
    if not threat_types or not rules:
        return None
    rows = [{"type": t, "class": rules[t]} for t in threat_types if t in rules]
    if not rows:
        return None
    min_class = max((r["class"] for r in rows), key=_class_rank)
    return {"uz": uz, "threat_types": threat_types, "rows": rows,
            "min_class": min_class}
